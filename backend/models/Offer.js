const mongoose = require('mongoose');

const offerSchema = new mongoose.Schema({
  requestId: { type: String },
  buyerUserId: { type: String, required: true },
  buyerId: { type: String },
  buyerName: { type: String, required: true },
  marketId: { type: String },
  marketName: { type: String },
  requirementId: { type: String },
  farmerUserId: { type: String, required: true },
  farmerId: { type: String },
  farmerName: { type: String, required: true },
  farmerMobile: { type: String },
  cropLotId: { type: String },
  cropName: { type: String, required: true },
  crop: { type: String },
  cropCategory: { type: String },
  variety: { type: String },
  offeredPrice: { type: Number },
  expectedPrice: { type: Number, required: true },
  minPrice: { type: Number },
  quantity: { type: Number, required: true },
  unit: { type: String, default: 'kg' },
  qualityGrade: { type: String, default: 'Grade A' },
  quality: { type: String, default: 'Grade A' },
  qualityRequired: { type: String, default: 'Grade A' },
  freshness: { type: String },
  description: { type: String },
  location: { type: String },
  farmerLocation: { type: String },
  state: { type: String },
  district: { type: String },
  village: { type: String },
  latitude: { type: Number },
  longitude: { type: Number },
  pickupLocation: { type: String },
  deliveryLocation: { type: String },
  distance: { type: Number, default: 45 },
  vehicleType: { type: String },
  transportCost: { type: Number },
  requestDate: { type: String },
  notes: { type: String },
  status: { type: String, default: 'REQUEST_SENT' },
  createdAt: { type: Date, default: Date.now }
});

module.exports = mongoose.model('Offer', offerSchema);

